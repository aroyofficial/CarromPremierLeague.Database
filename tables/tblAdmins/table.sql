CREATE TABLE IF NOT EXISTS tblAdmins (
    Id BIGINT NOT NULL AUTO_INCREMENT,
    CreatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UpdatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6)
    ON UPDATE CURRENT_TIMESTAMP(6),
    Void BOOLEAN NOT NULL DEFAULT FALSE,
    Username VARCHAR(100) NOT NULL,
    PasswordHash VARCHAR(128) NOT NULL,
    PasswordSalt VARCHAR(128) NOT NULL,
    PasswordIterations INT NOT NULL DEFAULT 310000,
    TokenVersion INT NOT NULL DEFAULT 1,
    IsActive BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT PK_tblAdmins PRIMARY KEY (Id),
    CONSTRAINT UQ_tblAdmins_Username UNIQUE (Username)
);
